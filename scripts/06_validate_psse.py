"""Validation level C: pandapower against PSS/E on representative hours.

Selects at least ten hours (seasons, demand levels, transfer extremes, highest loading),
writes them to config/representative_hours.yaml, solves each with pandapower from a flat
start, and compares voltages, plant reactive output, branch flows and losses with the PSS/E
solution.

Writes results/validation/psse_{summary,buses,branches,plants}.csv and the residual figure
results/figures/validation_psse.png.
"""

import pandas as pd
import yaml

from n44.config import configured_path, load_config, repo_path
from n44.io.build_net import build_net
from n44.io.dataset import Dataset
from n44.io.psse_parser import parse_raw
from n44.plotting import plot_validation_residuals
from n44.powerflow import run_ac
from n44.snapshots import SnapshotStore
from n44.validation import compare_hour, representative_hours
from n44.zones import EXCHANGE_LOAD_KEYS


def select_hours() -> pd.DataFrame:
    processed = configured_path("processed_dir")
    load_p = SnapshotStore().tables["load_p"]
    exchange_keys = {f"{bus}_{load_id}" for bus, load_id in EXCHANGE_LOAD_KEYS}
    demand = load_p[[c for c in load_p.columns if c not in exchange_keys]].sum(axis=1)
    hours = representative_hours(
        demand=demand,
        nordpool_exchange=pd.read_parquet(processed / "nordpool_exchange.parquet"),
        nordpool_production=pd.read_parquet(processed / "nordpool_production.parquet"),
        max_loading=pd.read_parquet(processed / "psse_consistency.parquet").max_loading_pct,
        calendar=pd.read_parquet(processed / "calendar.parquet"),
    )
    with open(repo_path("config", "representative_hours.yaml"), "w", encoding="utf-8") as fh:
        fh.write("# Generated by scripts/06_validate_psse.py; h = 24 * (day_of_year - 1) + hour\n")
        yaml.safe_dump(hours.to_dict("records"), fh, sort_keys=False)
    return hours


def main() -> None:
    hours = select_hours()
    ds = Dataset()
    summaries, buses, branches, plants = [], [], [], []
    for row in hours.itertuples():
        case = parse_raw(ds.raw_text(row.h, "after"))
        net = build_net(case)
        result = run_ac(net)
        if not result.converged:
            summaries.append({"h": row.h, "criterion": row.criterion, "converged": False})
            continue
        comparison = compare_hour(net, case)
        summaries.append(
            {
                "h": row.h,
                "criterion": row.criterion,
                "converged": True,
                "init": result.init,
                **comparison.summary,
            }
        )
        buses.append(comparison.buses.assign(h=row.h))
        branches.append(comparison.branches.reset_index().assign(h=row.h))
        plants.append(comparison.plants.assign(h=row.h))
    out = configured_path("results_dir") / "validation"
    out.mkdir(parents=True, exist_ok=True)
    summary = pd.DataFrame(summaries)
    summary.to_csv(out / "psse_summary.csv", index=False, float_format="%.6g")
    buses = pd.concat(buses).reset_index()
    branches = pd.concat(branches, ignore_index=True)
    buses.to_csv(out / "psse_buses.csv", index=False, float_format="%.7g")
    branches.to_csv(out / "psse_branches.csv", index=False, float_format="%.7g")
    pd.concat(plants).reset_index().to_csv(
        out / "psse_plants.csv", index=False, float_format="%.6g"
    )
    figure = plot_validation_residuals(
        buses,
        branches,
        load_config()["validation"],
        configured_path("results_dir") / "figures" / "validation_psse.png",
    )

    columns = [
        "h",
        "criterion",
        "max_dvm_pu",
        "max_dva_deg",
        "max_dp_branch_mw",
        "max_dq_branch_mvar",
        "slack_dp_mw",
        "losses_rel",
        "n_limited_ref",
        "limited_plants_match",
        "within_tolerance",
    ]
    with pd.option_context("display.width", 200, "display.max_colwidth", 32):
        print(summary[columns].to_string(index=False, float_format=lambda v: f"{v:.3g}"))
    print(f"\nAll hours within the tolerances: {bool(summary.within_tolerance.all())}")
    print(
        f"Worst over all hours: |dVm| {summary.max_dvm_pu.max():.2e} pu, |dVa| "
        f"{summary.max_dva_deg.max():.2e} deg, |dP| {summary.max_dp_branch_mw.max():.3f} MW, "
        f"|dQ| {summary.max_dq_branch_mvar.max():.3f} Mvar, slack "
        f"{summary.slack_dp_mw.abs().max():.3f} MW"
    )
    print(f"figure: {figure}")


if __name__ == "__main__":
    main()
